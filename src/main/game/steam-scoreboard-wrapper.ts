/** Steam launches GoldSrc from its own process, so the launch option is the
 * authoritative place to select the active match's native module. */
export function buildSteamScoreboardWrapper(directory: string, modulePath: string): string {
  const shellQuote = (value: string): string => `'${value.replaceAll("'", "'\\''")}'`
  return [
    '#!/bin/sh',
    `session=${shellQuote(directory)}`,
    `module=${shellQuote(modulePath)}`,
    'if [ -f "$session/overlay.enabled" ] && [ -f "$module" ]; then',
    '  # Steam can retain a module from an older launcher process. Keep only',
    '  # this match module while preserving unrelated preloads.',
    '  other_preloads=',
    '  set -f',
    '  IFS=" :"',
    '  for preload in ${LD_PRELOAD-}; do',
    '    case "$preload" in',
    '      */papamo-cosmetic-module-linux-x86.so) ;;',
    '      *) other_preloads="${other_preloads:+$other_preloads }$preload" ;;',
    '    esac',
    '  done',
    '  unset IFS',
    '  set +f',
    '  export LD_PRELOAD="$other_preloads"',
    '  # Steam overlay interposition also interferes with GoldSrc GL startup.',
    '  # Omit it only from the enhanced game, preserving Steam helpers and',
    '  # unrelated player preloads. Ordinary launches keep Steam overlay.',
    '  game_preloads=',
    '  set -f',
    '  IFS=" :"',
    '  for preload in $other_preloads; do',
    '    case "$preload" in',
    '      */ubuntu12_32/gameoverlayrenderer.so|*/ubuntu12_64/gameoverlayrenderer.so) ;;',
    '      *) game_preloads="${game_preloads:+$game_preloads }$preload" ;;',
    '    esac',
    '  done',
    '  unset IFS',
    '  set +f',
    '  # Do not load the module into Steam reaper or pressure-vessel. Its',
    '  # symbol interposition can conflict with the Steam overlay there.',
    '  # Insert env at the game command, inside the existing runtime chain.',
    '  remaining=$#',
    '  wrapped=',
    '  while [ "$remaining" -gt 0 ]; do',
    '    argument=$1',
    '    shift',
    '    remaining=$((remaining - 1))',
    '    case "$argument" in',
    '      */hl.sh|*/hl_linux|hl.sh|hl_linux)',
    '        if [ -z "$wrapped" ]; then',
    '          set -- "$@" /usr/bin/env "PAPAMO_SKIN_PROBE_SESSION=$session" "LD_PRELOAD=$module${game_preloads:+ $game_preloads}"',
    '          wrapped=1',
    '        fi ;;',
    '    esac',
    '    set -- "$@" "$argument"',
    '  done',
    '  # Unknown Steam commands remain usable with their original preloads.',
    'fi',
    'exec "$@"',
    ''
  ].join('\n')
}
