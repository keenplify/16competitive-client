export const translateRuntimeText = (language: LanguageCode, source: string): string => {
  if (language === 'en' || !source) return source
  const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/)
  if (!match) return source
  const [, leading, body, trailing] = match
  if (!body) return source

  const exact = catalogs[language][body]
  if (exact !== undefined) return `${leading}${exact}${trailing}`

  let translated = body
  for (const [pattern, replacement] of dynamic[language]) {
    if (pattern.test(body)) {
      translated = body.replace(pattern, replacement)
      break
    }
  }
  return `${leading}${translated}${trailing}`
}
